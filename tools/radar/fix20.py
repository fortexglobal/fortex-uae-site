import sys
p = sys.argv[1] if len(sys.argv) > 1 else '/opt/radar/radar.py'
s = open(p, encoding='utf-8').read()

# поле hit в оценке нейросети: прямое / косвенное / нет
a = '"tier": "бизнес|состоятельный частный|мелкий|непонятно", '
if '"hit"' not in s:
    if a in s:
        s = s.replace(a, '"hit": "прямое|косвенное|нет", ' + a, 1)
        rules = '''ПОПАДАНИЕ (поле hit):
прямое: человек спрашивает или пишет о проблеме именно по счетам и банкам в ОАЭ, ВНЖ и визам ОАЭ, Emirates ID, компаниям в ОАЭ (фризона, mainland, лицензия). Любой человек, не важно, богатый или нет.
косвенное: платёжные агенты, переводы и оплаты за границу, карты, расчёты с Китаем, ВЭД, а также любой разговор человека с деньгами или бизнесом.
нет: всё остальное, в том числе визы и счета других стран без связи с ОАЭ, бытовые темы Дубая (еда, жильё, такси), реклама, новости.

'''
        b = 'НАШ КЛИЕНТ (главный фильтр):'
        c = 'Оцени сообщение и ответь строго JSON'
        if b in s:
            s = s.replace(b, rules + b, 1)
        elif c in s:
            s = s.replace(c, rules + c, 1)
        print('FIX20 hit field added')
    else:
        print('FIX20 WARN: prompt anchor not found, работаем по ключевым словам')
open(p, 'w', encoding='utf-8').write(s)
print('FIX20_OK')
